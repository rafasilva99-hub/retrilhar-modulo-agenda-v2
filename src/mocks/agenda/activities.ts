// ─────────────────────────────────────────────────────────────────────────────
// Dynamic date helpers — all dates relative to today
// ─────────────────────────────────────────────────────────────────────────────

function dayOffset(offset: number): string {
  const d = new Date();
  d.setDate(d.getDate() + offset);
  return d.toISOString().slice(0, 10); // YYYY-MM-DD
}

